/// One fixture of the contract (ADR-024 §7): a test JSON, the rules the Dart
/// pipeline reports as errors for it, and the rules the SQL shape check must
/// name.
///
/// The SQL check is a subset of `checkTopikTest`, so for a JSON the mapper
/// reads, [sqlRules] are among [dartErrorRules]. A JSON the mapper itself
/// refuses (Dart reports only `shape`) is judged differently: both sides
/// reject it, and [bothReject] is true.
final class ContractFixture {
  ContractFixture(this.name, this.json, {required this.sqlRules})
    : dartErrorRules = {
        for (final issue in topikContentOf([
          (origin: '$name.json', json: json),
          // Assets are outside the SQL check, so the contract is silent on them
          // by design: every asset path counts as present.
        ], assetExists: (_) => true).issues)
          if (issue.isError) issue.rule.name,
      };

  final String name;
  final Map<String, Object?> json;
  final Set<String> sqlRules;
  final Set<String> dartErrorRules;

  /// The mapper refuses the JSON, so `checkTopikTest` never ran on it.
  bool get bothReject => dartErrorRules.contains('shape');
}

Map<String, Object?> _copy(Map<String, Object?> json) =>
    jsonDecode(jsonEncode(json)) as Map<String, Object?>;

Map<String, Object?> _mutated(void Function(Map<String, Object?> json) edit) {
  final json = _copy(topikTestJson());
  edit(json);
  return json;
}

Map<String, Object?> _question(Map<String, Object?> json, int index) =>
    (json['questions'] as List<Object?>)[index] as Map<String, Object?>;

List<ContractFixture> topikContractFixtures() => [
  for (final level in TopikLevel.values)
    for (final section in TopikSection.values)
      ContractFixture(
        '${level.code}-${section.code}-valid',
        topikTestJson(level: level, section: section),
        sqlRules: const {},
      ),
  ContractFixture(
    'identity-wrong-test-id',
    _mutated((j) => j['testId'] = 'topik2-95-reading'),
    sqlRules: const {'identity'},
  ),
  ContractFixture(
    'metadata-publisher',
    _mutated(
      (j) => (j['source'] as Map<String, Object?>)['publishedBy'] = 'ETS',
    ),
    sqlRules: const {'metadata'},
  ),
  ContractFixture(
    'numbering-missing-question',
    _mutated((j) => (j['questions'] as List<Object?>).removeLast()),
    sqlRules: const {'numbering', 'points', 'groups'},
  ),
  ContractFixture(
    'points-three',
    _mutated((j) => _question(j, 0)['points'] = 3),
    sqlRules: const {'points'},
  ),
  ContractFixture(
    'options-answer-5',
    _mutated((j) => _question(j, 0)['answerIdx'] = 5),
    sqlRules: const {'options'},
  ),
  ContractFixture(
    'groups-unknown-group',
    _mutated((j) => _question(j, 0)['groupId'] = 'nope'),
    sqlRules: const {'groups'},
  ),
  // The mapper refuses a wrongly-typed field (Dart: shape); the SQL check
  // reads `questions` as no questions at all and names what then fails.
  ContractFixture(
    'shape-questions-not-array',
    _mutated((j) => j['questions'] = 'x'),
    sqlRules: const {'numbering', 'points', 'groups'},
  ),
  // A required key is absent: the mapper refuses it (Dart: shape). The SQL check
  // must reject it too, whatever it names.
  ContractFixture(
    'shape-missing-level',
    _mutated((j) => j.remove('level')),
    sqlRules: const {'identity'},
  ),
  ContractFixture(
    'shape-missing-section',
    _mutated((j) => j.remove('section')),
    sqlRules: const {'identity'},
  ),
  ContractFixture(
    'shape-question-without-points',
    _mutated((j) => _question(j, 0).remove('points')),
    sqlRules: const {'points'},
  ),
  ContractFixture(
    'languages-missing-en',
    _mutated((j) => _question(j, 0)['explanation'] = {'vi': 'x'}),
    sqlRules: const {'languages'},
  ),
];

String _sorted(Set<String> rules) => (rules.toList()..sort()).join(',');

/// Every generated file, by its repo-relative path.
Map<String, String> renderTopikContractFiles() {
  final all = topikContractFixtures();
  const encoder = JsonEncoder.withIndent('  ');
  final files = <String, String>{
    for (final f in all)
      'test/fixtures/topik/${f.name}.json': '${encoder.convert(f.json)}\n',
  };
  final sql = StringBuffer()
    ..writeln(
      '-- GENERATED by test/tools/topik_fixtures_export_test.dart '
      '(MEMOX_UPDATE_FIXTURES=1) — DO NOT EDIT',
    )
    ..writeln(
      '-- ADR-024 §7: the SQL shape check is a subset of checkTopikTest on '
      'every fixture the Dart mapper reads;',
    )
    ..writeln('-- a fixture the mapper refuses is rejected by both sides.')
    ..writeln('begin;')
    ..writeln('create extension if not exists pgtap with schema extensions;')
    ..writeln('select plan(${all.length * 2});');
  for (final f in all) {
    final json = jsonEncode(f.json).replaceAll("'", "''");
    final call = "private.topik_master_shape_issues('$json'::jsonb)";
    final rules = _sorted(f.sqlRules);
    // The SQL check lists its rules in its own order; the contract is the set.
    final sortedCall = 'array(select r from unnest($call) as r order by r)';
    if (f.bothReject) {
      sql
        ..writeln(
          "select ok(array_length($call, 1) > 0,\n"
          "  '${f.name}: Dart refuses the JSON (shape) and the SQL rejects it too');",
        )
        ..writeln(
          "select is($sortedCall, '{$rules}'::text[],\n"
          "  '${f.name}: the SQL rules are exactly ${rules.isEmpty ? 'none' : rules}');",
        );
      continue;
    }
    final dart = _sorted(f.dartErrorRules);
    sql
      ..writeln(
        "select ok($call <@ '{$dart}'::text[],\n"
        "  '${f.name}: the SQL rules are among the Dart errors');",
      )
      ..writeln(
        "select is($sortedCall, '{$rules}'::text[],\n"
        "  '${f.name}: the SQL rules are exactly ${rules.isEmpty ? 'none' : rules}');",
      );
  }
  sql
    ..writeln('select * from finish();')
    ..writeln('rollback;');
  files['supabase/tests/database/19_topik_master_fixtures.sql'] = sql
      .toString();
  return files;
}
